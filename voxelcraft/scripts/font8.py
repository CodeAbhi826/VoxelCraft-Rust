#!/usr/bin/env python3
"""Rewrite the ui.rs FONT table: 7-row -> 8-row glyphs (baseline row 6,
descender row 7 — vanilla font metrics) and give the a-z slots TRUE
lowercase shapes (they held uppercase dummies for the smallcaps remap).
Also drops the period/comma/colon onto the new baseline. The smallcaps
remap in text()/text_flat()/text_splash() stays, so all existing UI
rendering is unchanged; the new case renderer (F3) uses the lowercase
slots directly."""
import re, sys

UI = "/home/z/my-project/voxelcraft/crates/vc-render/src/ui.rs"
src = open(UI, encoding="utf-8").read()

m = re.search(r"const FONT: \[\[u8; 7\]; 96\] = \[\n(.*?)\n\];", src, re.S)
if not m:
    sys.exit("FONT table not found")
body = m.group(1)
glyphs = re.findall(r"\[([0-9xXa-fA-F,]+)\]", body)
assert len(glyphs) == 96, f"expected 96 glyphs, got {len(glyphs)}"

def parse(s):
    v = [int(x, 16) for x in s.split(",")]
    assert len(v) == 7, f"7 rows expected, got {len(v)}"
    return v

# true lowercase (5 wide, 8 rows: x-height rows 2..6, ascenders 0..6,
# descenders 2..7). Clean-room shapes with vanilla-like proportions
# (narrow arch letters, 1-px i, t/l foot+hook).
LC = {
    "a": [0x00,0x00,0x0E,0x01,0x0F,0x11,0x0F,0x00],
    "b": [0x10,0x10,0x1C,0x12,0x12,0x12,0x1C,0x00],
    "c": [0x00,0x00,0x0E,0x11,0x10,0x11,0x0E,0x00],
    "d": [0x02,0x02,0x0E,0x12,0x12,0x12,0x0E,0x00],
    "e": [0x00,0x00,0x0E,0x11,0x1F,0x10,0x0E,0x00],
    "f": [0x0C,0x04,0x1E,0x04,0x04,0x04,0x04,0x00],
    "g": [0x00,0x00,0x0E,0x11,0x11,0x0E,0x01,0x0F],
    "h": [0x10,0x10,0x1C,0x12,0x12,0x12,0x12,0x00],
    "i": [0x00,0x04,0x00,0x04,0x04,0x04,0x04,0x00],
    "j": [0x00,0x04,0x00,0x04,0x04,0x04,0x04,0x0C],
    "k": [0x10,0x10,0x12,0x14,0x18,0x14,0x12,0x00],
    "l": [0x04,0x04,0x04,0x04,0x04,0x04,0x06,0x00],
    "m": [0x00,0x00,0x1B,0x15,0x15,0x15,0x15,0x00],
    "n": [0x00,0x00,0x1C,0x12,0x12,0x12,0x12,0x00],
    "o": [0x00,0x00,0x0E,0x11,0x11,0x11,0x0E,0x00],
    "p": [0x10,0x10,0x1C,0x12,0x12,0x12,0x1C,0x10],
    "q": [0x02,0x02,0x0E,0x12,0x12,0x12,0x0E,0x02],
    "r": [0x00,0x00,0x1C,0x14,0x10,0x10,0x10,0x00],
    "s": [0x00,0x00,0x0F,0x10,0x0E,0x01,0x1E,0x00],
    "t": [0x04,0x0E,0x04,0x04,0x04,0x04,0x06,0x00],
    "u": [0x00,0x00,0x12,0x12,0x12,0x12,0x1E,0x00],
    "v": [0x00,0x00,0x11,0x11,0x11,0x0A,0x04,0x00],
    "w": [0x00,0x00,0x11,0x11,0x11,0x15,0x0A,0x00],
    "x": [0x00,0x00,0x11,0x0A,0x04,0x0A,0x11,0x00],
    "y": [0x00,0x00,0x11,0x11,0x11,0x0A,0x04,0x0C],
    "z": [0x00,0x00,0x1F,0x02,0x04,0x08,0x1F,0x00],
}
# punctuation re-seated on the new baseline (descender row for the tail)
PUNCT = {
    ord("."): [0x00,0x00,0x00,0x00,0x00,0x0C,0x0C,0x00],
    ord(","): [0x00,0x00,0x00,0x00,0x00,0x04,0x04,0x08],
    ord(":"): [0x00,0x00,0x0C,0x0C,0x00,0x0C,0x0C,0x00],
    ord(";"): [0x00,0x00,0x0C,0x0C,0x00,0x0C,0x04,0x08],
}

rows = []
for i, g in enumerate(glyphs):
    asc = 32 + i
    if asc in PUNCT:
        new = PUNCT[asc]
    elif ord("a") <= asc <= ord("z"):
        new = LC[chr(asc)]
    else:
        new = parse(g) + [0x00]
    rows.append(new)

def fmt(g):
    return "[" + ",".join(f"0x{v:02X}" for v in g) + "]"

lines = []
for i in range(0, 96, 2):
    a = fmt(rows[i])
    if i + 1 < 96:
        lines.append(f"    {a}, {fmt(rows[i+1])},")
    else:
        lines.append(f"    {a},")
table = "\n".join(lines)

header = (
    "// 5x8 font, rows top→bottom, bit 4 = leftmost pixel. ASCII 32..127.\n"
    "// Rows 0..6 = the smallcaps body (caps/digits/punct sit on the row-6\n"
    "// baseline); row 7 = the descender row (g j p q y ,). The a-z slots\n"
    "// hold TRUE lowercase shapes — only the case renderer (F3 overlay)\n"
    "// reads them; text()/text_flat() remap a-z→A (smallcaps UI look).\n"
    "const FONT: [[u8; 8]; 96] = [\n"
)
new_block = header + table + "\n];"
src = src[: m.start()] + new_block + src[m.end():]
open(UI, "w", encoding="utf-8").write(src)
print("FONT rewritten: 96 glyphs x 8 rows; a-z = true lowercase; . , : ; re-baselined")
